type WebServerConfig struct {
	Driver    string
	Dsn       string
	Domain    string
	IP        string
	Listen    string
	Swagger   bool
	WithGuest bool
	TestMode  bool

	// RedisAddr is an optional Redis address for HA session sharing.
	// If empty, MCP sessions use in-memory storage.
	RedisAddr string

	AuthExpire                   time.Duration
	DefaultCleanInterval         int64
	DefaultQueryApiMaxItem       int
	DefaultMaxCallbackErrorCount int64
	DefaultLanguage              string
	AnonymousMode                bool `json:"anonymous_mode"` // when true, don't record real source IPs

	// GeoIP configuration. MMDBPath is the location of GeoLite2-ASN.mmdb.
	// LicenseKey enables auto-download when the file is missing.
	GeoIPMMDBPath   string
	GeoIPLicenseKey string

	CaptchaEnabled bool          `json:"captcha_enabled"` // default true
	CaptchaExpire  time.Duration // default 2min

	// TLS configuration for standalone deployment mode.
	// When TLSMode is not "disabled", the server uses HTTPS.
	TLSMode     string
	TLSCertFile string
	TLSKeyFile  string
	ACMEEmail   string
	CertDir     string

	// Demo mode configuration.
	// When DemoMode is true, demo users and sample data are created.
	DemoMode       bool
	DemoResetHours int
}

